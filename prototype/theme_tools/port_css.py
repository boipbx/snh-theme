"""Port prototype/css/proto.css to assets/snh-v2.css for the Shopify theme.

- class names that collide with Impact's theme.css get a v- prefix (btn, section, h1, ...)
- --accent / --radius tokens become --v-accent / --v-radius (Impact defines both)
- element resets are scoped to :where(.v2) so they never beat a component class
- the prototype-only "show editable areas" toggle is dropped
One-time port (round 5): assets/snh-v2.css was generated by this script and then extended by hand,
so re-running it overwrites those edits. Kept as a record of the renames.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / "prototype/css/proto.css").read_text()

COLLIDE = "btn|section|h1|h2|wrap|link|badge|input|offer|prose|rating|reveal|tabs"
RENAME = re.compile(r"\.(" + COLLIDE + r")(?![a-zA-Z0-9])")


def port(css):
    # base element rules -> scoped
    css = re.sub(r"/\* ---------- base ---------- \*/.*?(?=\.wrap \{)", BASE, css, flags=re.S)
    css = re.sub(r"/\* \"Show editable areas\" demo toggle \*/.*?(?=/\* ---------- 3\.)", "", css, flags=re.S)
    css = re.sub(r"@media \(max-width: 1023px\) \{ \.edit-toggle \{ display: none; \} \}\n", "", css)
    css = RENAME.sub(lambda m: ".v-" + m.group(1), css)
    css = re.sub(r"var\(--(accent|accent-hover|radius)\)", r"var(--v-\1)", css)
    css = re.sub(r"(\n\s*)--(accent|accent-hover|radius):", r"\1--v-\2:", css)
    css = css.replace(".js ", ".v-js ")
    css = css.replace('url("data:image/svg+xml,%3Csvg xmlns=\'http://www.v-w3', 'url("data:image/svg+xml,%3Csvg xmlns=\'http://www.w3')
    return css


BASE = """/* ---------- base (scoped: only inside v2 sections, zero specificity) ---------- */
:where(.v2) { font-family: var(--sans); color: var(--ink); -webkit-font-smoothing: antialiased; }
:where(.v2) img { display: block; max-width: 100%; height: auto; }
:where(.v2) a { color: inherit; text-decoration: none; }
:where(.v2) button { font: inherit; color: inherit; }
:where(.v2) :is(h1, h2, h3, h4, p, figure, blockquote) { margin: 0; color: inherit; text-transform: none; }
:where(.v2) :is(ul, ol) { margin: 0; padding: 0; list-style: none; }
:where(.v2) :focus-visible { outline: 2px solid var(--v-accent); outline-offset: 3px; border-radius: 4px; }

"""

out = port(src)
(ROOT / "assets/snh-v2.css").write_text(out)
print("wrote", len(out), "bytes")
