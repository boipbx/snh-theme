"""Writes images/IMAGE-SOURCES.md from registry.py (what is used, where) and the theme audit TSVs.
Called at the end of build.py so the document always matches the built pages."""
import re
from pathlib import Path

import registry as R

HERE = Path(__file__).parent
LOW_RES = 1000  # anything narrower than this is flagged: soft on retina at hero/feature sizes

LOGO_PAT = re.compile(r"logo|brand_logo|Untitled_design\.zip|Untitled_1000_x_1500|Untitled_240_x_240|Untitled_2800_x_1200|^IMG_00(45|46|49)\.", re.I)
TEXT_PAT = re.compile(r"_desk|_desktop|_mobile|desk\.jpg|mobile\.jpg|Social_|SALE_banner|landing_page|website_cover|LOGO_SNH|Screenshot_|test_desk|test_mobile|sex.bomb|creatine_desk|creatine_mobile", re.I)


# visually checked on the contact sheets; overrides the filename heuristics
OVERRIDE = {
    "2fd50e25-5d19-4f08-9e36-f8992b6e917c.jpg": "Text baked in (checked)",
    "d15b04ae-74cb-46b8-ab36-d6e467b4ddce.jpg": "Text baked in (checked)",
    "brand_of_the_month_-_ryse.jpg": "Text baked in (checked)",
    "3020822f-af0f-469f-928b-eb220c28cda5.jpg": "Text baked in (checked)",
    "ce1e57ec-0a81-4190-9f98-3e0756910eec.jpg": "Text baked in (checked)",
    "IMG_3154.jpg": "Text baked in (checked)",
    "running.jpg": "Photo, no text (checked)", "cricket.jpg": "Photo, no text (checked)",
    "the-sulek-stack.jpg": "Photo, no text (checked)", "the-sulek-stack_mobike.jpg": "Photo, no text (checked)",
    "ryse-desk-banner.jpg": "Photo, no text (checked)", "revive.jpg": "Photo, no text (checked)",
    "nootropics-web-cover.jpg": "Photo, no text (checked)",
    "ehp_labs_landing_page_2.jpg": "Text baked in (checked)", "padel_mobile_landing_page_1.jpg": "Text baked in (checked)",
}


def classify(fn, w):
    if fn in OVERRIDE and w:
        return OVERRIDE[fn], ""
    if fn.startswith(R.GENERATED_NAME_PREFIX):
        return "Generated (filename)", "Excluded"
    if fn in R.SUSPECTED_GENERATED:
        return "Suspected generated (same orange-studio series)", "Excluded: confirm with the team"
    if w == 0:
        return "Missing on CDN (404)", "Broken reference in theme"
    if LOGO_PAT.search(fn):
        return "Logo / wordmark (text)", ""
    if TEXT_PAT.search(fn):
        return "Text baked in (likely)", ""
    return "Photo, no text (likely)", ""


def write():
    used = []
    for key, (url, w, h, baked, source, note) in R.IMAGES.items():
        places = sorted(R.USED_IN.get(key, []))
        if not places:
            continue
        flags = []
        if w < LOW_RES:
            flags.append("**LOW-RES**")
        if baked:
            flags.append("text baked in")
        used.append(f"| `{key}` | {'<br>'.join(places)} | [{url.split('/')[-1].split('?')[0]}]({url}) | {source} | {w}×{h} | {'Yes' if baked else 'No'} | {' · '.join(flags + ([note] if note else []))} |")

    rows = [l.rstrip("\n").split("\t") for l in open(HERE / "theme-images.tsv")]
    dims = {l.split("\t")[0]: l.rstrip("\n").split("\t")[1:] for l in open(HERE / "theme-dims.tsv")}
    audit, counts = [], {}
    for fn, n, where in rows:
        w, h = (int(x) for x in dims.get(fn, ["0", "0"]))
        kind, status = classify(fn, w)
        counts[kind] = counts.get(kind, 0) + 1
        audit.append(f"| [{fn}]({R.SNH}{fn}) | {w}×{h} | {kind} | {status} | {where.replace('|', '·')} |")

    missing = [
        ("Hero / promo: new brands launch", "No clean 'new brands' artwork exists. The banner slide shows the existing SNH × Padel League partner banner as the banner-type example"),
        ("Revive Magnesium Glycinate packshot", "revivemd.com is an unrelated site (a medical spa, VitalizeMD); no official source found"),
        ("Colombo Aces athletes (×4)", "No partner photography in the theme or online"),
        ("Bundles promo tile", "The only bundle images (bundle_off/wellness/protines.png) are suspected generated"),
        ("Google review quotes", "Text, not images. Pull from the Google Reviews app"),
        ("MuscleTech, Myprotein, Redcon1, RYSE, EHP Labs, Healthspan campaign images", "Not needed by the current prototype; muscletech.com blocks automated access"),
    ]

    md = f"""# Image sources — SNH prototype

Generated by `build.py` from `images/registry.py`. Every image is **hotlinked** (fine for a demo, not for production).
Low-res = narrower than {LOW_RES}px (soft on retina at hero/feature sizes).

## 1. Images used in the prototype ({len(used)})

| Key | Where it appears | File | Source | Size | Baked-in text | Notes |
|---|---|---|---|---|---|---|
{chr(10).join(used)}

## 2. Still missing (shown as labelled grey placeholders)

| Slot | Why |
|---|---|
{chr(10).join(f"| {a} | {b} |" for a, b in missing)}

## 3. Audit of every image in the current theme's homepage + collection + landing templates ({len(rows)})

`shopify://shop_images/<file>` resolves to `{R.SNH}<file>` (checked against the live homepage HTML; 49 of these appear on it today).
Classification is by filename pattern plus a visual check of contact sheets. Rows marked *likely* still need a final look.

| Category | Count |
|---|---|
{chr(10).join(f"| {k} | {v} |" for k, v in sorted(counts.items(), key=lambda x: -x[1]))}

| File | Size | Classification | Status | Used in (first 3) |
|---|---|---|---|---|
{chr(10).join(audit)}

## 4. Fetch attempts (images/fetch-log.tsv)

Every external image, video or page fetch attempt, in order. Rule: retry with a different URL, user agent or rendition path
(add/drop `/.renditions/`); a placeholder is only used after 3 real failed attempts.

| Time | Key | Attempt | URL | User agent | Result |
|---|---|---|---|---|---|
{chr(10).join("| " + " | ".join(c.replace("|", "/") for c in line.split(chr(9))) + " |" for line in (HERE / "fetch-log.tsv").read_text().splitlines()[1:] if line.strip())}
"""
    (HERE / "IMAGE-SOURCES.md").write_text(md)
    return len(used), len(rows)
